/* Generate bilingual standalone NPC story entries from the public NPC/quest/service records. */
const fs = require('node:fs');
const path = require('node:path');
const { renderSiteFooter } = require('./render-site-footer.cjs');
const { renderNpcStory, storyReferenceAssets, storySearchText, safeNpcSummary, safeNpcWhenNeeded } = require('./render-npc-story.cjs');

const root = path.resolve(__dirname, '..');
const npcs = require('../data/npcs.json').npcs;
const quests = require('../data/quests.json').quests;
const services = require('../data/dialogue-services.json').services;
const scenes = require('../data/dialogue-scenes.json').scenes;
const checkOnly = process.argv.includes('--check');
const esc = value => String(value ?? '').replace(/[&<>"']/g, c => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' }[c]));

const nav = locale => {
  const zh = locale === 'zh';
  const links = zh
    ? [['/zh/guides/beginners-guide', '攻略'], ['/zh/database', '资料库'], ['/zh/map', '地图'], ['/zh/problems', '问题'], ['/research', '研究'], ['/zh/search', '搜索'], ['/contribute', '投稿']]
    : [['/guides/beginners-guide', 'Guides'], ['/database', 'Database'], ['/map', 'Map'], ['/problems', 'Problems'], ['/research', 'Research'], ['/search', 'Search'], ['/contribute', 'Contribute']];
  return links.map(([href, label]) => `<li><a href="${href}">${label}</a></li>`).join('');
};

function sourceLabel(scene, locale) {
  const ids = scene.evidence?.sourceIds || [];
  return `${locale === 'zh' ? '本站整理 · ' : 'Site-collected · '}${scene.status === 'configured-plus-community' ? (locale === 'zh' ? '构建配置与社区资料' : 'build configuration and community evidence') : (locale === 'zh' ? '构建配置' : 'build configuration')} · ${ids.join(', ')}`;
}

function shell(locale, npc, body) {
  const zh = locale === 'zh';
  const prefix = zh ? '/zh' : '';
  const route = `${prefix}/database/npcs/${npc.id}`;
  const alternate = zh ? `/database/npcs/${npc.id}` : `/zh/database/npcs/${npc.id}`;
  const title = zh ? `${npc.zhName}：人物、任务与对话 | The Ranchers Guide` : `${npc.name}: quests, services & dialogue | The Ranchers Guide`;
  const summary = safeNpcSummary(npc, locale);
  const description = zh ? `${summary} 查看相关任务、服务和防剧透对话摘要。` : `${summary} See related quests, services and spoiler-safe dialogue summaries.`;
  return `<!DOCTYPE html>\n<!-- GENERATED by scripts/build-npc-entries.cjs from data/npcs.json and data/dialogue-scenes.json — do not edit directly. -->\n<html lang="${zh ? 'zh-CN' : 'en'}"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>${esc(title)}</title><meta name="description" content="${esc(description)}"><link rel="canonical" href="https://theranchersguide.com${route}"><link rel="alternate" hreflang="en" href="https://theranchersguide.com${zh ? alternate : route}"><link rel="alternate" hreflang="zh-CN" href="https://theranchersguide.com${zh ? route : alternate}"><link rel="alternate" hreflang="x-default" href="https://theranchersguide.com${zh ? alternate : route}"><meta property="og:type" content="article"><meta property="og:site_name" content="The Ranchers Guide"><meta property="og:title" content="${esc(title)}"><meta property="og:description" content="${esc(description)}"><meta property="og:url" content="https://theranchersguide.com${route}"><link rel="icon" type="image/png" sizes="32x32" href="/assets/img/favicon-32.png"><link rel="stylesheet" href="/assets/css/style.css?v=20261003-r15"><link rel="stylesheet" href="/assets/css/database-browser.css?v=20260831-1">${storyReferenceAssets('20261005-r21')}<script async src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-4804883741146501" crossorigin="anonymous"></script></head><body class="database-surface"><header class="site-header"><nav class="nav-inner" aria-label="${zh ? '主导航' : 'Main navigation'}"><a class="logo" href="${zh ? '/zh/' : '/'}"><span class="logo-mark"><img src="/assets/img/logo.png" alt="" width="34" height="34"></span><span>The Ranchers Guide</span></a><button class="nav-toggle" aria-expanded="false" aria-label="${zh ? '展开导航' : 'Toggle navigation'}">☰</button><ul class="nav-links">${nav(locale)}</ul></nav></header><main><article class="article database-page npc-story-entry" data-search-entry id="${esc(npc.id)}" data-search-title="${esc(zh ? npc.zhName : npc.name)}" data-search-text="${esc(storySearchText(npc, locale))}" data-search-aliases="${esc((npc.searchAliases || []).join('|'))}" data-search-tags="${esc(searchTags(locale, npc))}" data-search-status="${zh ? '人物故事条目' : 'NPC story entry'}">${body}</article></main>${renderSiteFooter(locale, { en: 'Source-linked NPC story entry', zh: '来源关联的人物故事条目' })}<script src="/assets/js/main.js?v=20261003-r15" defer></script></body></html>`;
}

function render(locale, npc) {
  const zh = locale === 'zh';
  const prefix = zh ? '/zh' : '';
  const relatedScenes = scenes.filter(scene => scene.npcId === npc.id);
  if (!relatedScenes.length) return null;
  const sceneQuestIds = [...new Set(relatedScenes.flatMap(scene => scene.questIds || []))];
  const sceneServiceIds = [...new Set(relatedScenes.flatMap(scene => scene.serviceIds || []))];
  const relatedQuests = quests.filter(quest => sceneQuestIds.includes(quest.id));
  const relatedServices = services.filter(service => sceneServiceIds.includes(service.id));
  const dialogue = {
    status: 'configured',
    sourceLabel: sourceLabel(relatedScenes[0], 'en'),
    zhSourceLabel: sourceLabel(relatedScenes[0], 'zh'),
    build: relatedScenes[0].evidence?.build,
    groups: relatedScenes.flatMap(scene => (scene.groups || []).map(group => ({
      ...group,
      sceneId: scene.id,
      sceneTitle: scene.title,
      zhSceneTitle: scene.zhTitle,
    }))),
  };
  const story = renderNpcStory(npc, { locale, services: relatedServices, quests: relatedQuests, dialogue });
  const sceneCards = relatedScenes.map(scene => {
    const title = zh ? scene.zhTitle : scene.title;
    const spoilerSafeSummary = scene.id === 'gigi-egg-route'
      ? (zh ? '已记录的大鸡蛋任务路线；展开对话预览后再查看节点细节。' : 'Recorded large-egg task route; expand the dialogue preview for node details.')
      : (zh ? scene.zhSummary : scene.summary);
    const topics = (zh ? scene.zhTopics : scene.topics).map(topic => `<span class="tag evidence-lead">${esc(topic)}</span>`).join(' ');
    const questLinks = (scene.questIds || []).map(id => {
      const quest = quests.find(item => item.id === id);
      if (!quest) return '';
      return `<a class="btn btn-outline btn-compact" href="${prefix}/database/quests#${esc(id)}">${esc(zh ? quest.zhName : quest.name)}</a>`;
    }).join(' ');
    return `<section class="story-scene-card" id="scene-${esc(scene.id)}"><h2>${esc(title)}</h2><p>${esc(spoilerSafeSummary)}</p><p class="story-scene-topics">${topics}</p><p class="fact-source"><strong>${zh ? '边界' : 'Boundary'}:</strong> ${esc(zh ? '配置资料或现有社区资料，未把未知运行时条件写成确定答案。' : 'Configured or existing community evidence; unknown runtime conditions are not upgraded to facts.')}</p><div class="entity-related"><strong>${zh ? '继续查找' : 'Continue with'}</strong><div>${questLinks}</div></div></section>`;
  }).join('\n');
  const safeSummary = safeNpcSummary(npc, locale);
  const safeWhenNeeded = safeNpcWhenNeeded(npc, locale);
  const shopCheck = npc.relatedRoutes?.includes('/guides/animal-guide#shop-locked')
    ? `<p><a class="btn btn-outline btn-compact" href="${prefix}/guides/animal-guide#shop-locked">${zh ? '购买选项消失？检查心形与送礼' : 'Purchase option missing? Check hearts and gifts'}</a></p>`
    : '';
  return `<nav class="breadcrumb" aria-label="${zh ? '面包屑' : 'Breadcrumb'}"><a href="${prefix}/">${zh ? '首页' : 'Home'}</a> / <a href="${prefix}/database/npcs">${zh ? '人物' : 'NPCs'}</a> / ${esc(zh ? npc.zhName : npc.name)}</nav><a class="database-back" href="${prefix}/database/npcs">${zh ? '返回人物目录' : 'Back to NPC directory'}</a><h1>${esc(zh ? npc.zhName : npc.name)}</h1><p class="meta">${zh ? '人物条目 · 来源与版本边界可展开查看' : 'NPC entry · expand source and version boundaries as needed'}</p><p class="lead">${esc(safeSummary)}</p><p class="npc-when-needed"><strong>${zh ? '什么时候查找：' : 'When to look here: '}</strong>${esc(safeWhenNeeded)}</p>${shopCheck}${story}<div class="story-scenes"><h2>${zh ? '对话主题与任务连接' : 'Conversation topics and quest links'}</h2>${sceneCards}</div>`;
}

function searchTags(locale, npc) {
  if (npc.id === 'gigi') return locale === 'zh' ? 'Gigi 吉吉 大鸡蛋 任务' : 'Gigi large egg task';
  return locale === 'zh' ? npc.zhSearchTags : npc.searchTags;
}

let failed = false;
for (const npc of npcs) {
  if (!scenes.some(scene => scene.npcId === npc.id)) continue;
  for (const locale of ['en', 'zh']) {
    const file = path.join(root, locale === 'zh' ? 'zh' : '', 'database', 'npcs', `${npc.id}.html`);
    const html = shell(locale, npc, render(locale, npc));
    if (checkOnly) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== html) { console.error(`FAIL: ${file} is out of sync`); failed = true; }
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, html, 'utf8');
    }
  }
}
if (failed) process.exit(1);
console.log(`PASS: ${scenes.filter(scene => npcs.some(npc => npc.id === scene.npcId)).length} NPC story scenes generated; ${npcs.filter(npc => scenes.some(scene => scene.npcId === npc.id)).length} NPC profiles × 2 locales.`);
