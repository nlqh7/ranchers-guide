/* Build the first B2 bilingual task/material entries from the existing source records. */
const fs = require('node:fs');
const path = require('node:path');
const { renderSiteFooter } = require('./render-site-footer.cjs');

const root = path.resolve(__dirname, '..');
const config = require('../data/b2-entry-pages.json');
const questsData = require('../data/quests.json');
const materialsData = require('../data/materials.json');
const resourceData = require('../data/build-resources.json');
const buildingEntries = require('../data/building-entries.json');
const shops = require('../data/build-shops.json');
const materials = materialsData.materials;
const quests = questsData.quests;
const materialRoutes = {
  ressource_wood: 'wood-log',
  ressource_rock_simple: 'stone',
  ressource_straw: 'hay',
};
const esc = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
const prefixFor = locale => locale === 'zh' ? '/zh' : '';
const copy = (locale, en, zh) => locale === 'zh' ? zh : en;

function localizeRoute(route, locale) {
  if (locale !== 'zh') return route;
  if (route === '/community') return '/zh/community';
  if (route.startsWith('/database/') || route.startsWith('/guides/') || route.startsWith('/map')) return `/zh${route}`;
  return route;
}

function sourceHtml(data, ids, locale) {
  return ids.map(id => {
    const source = data.sources[id];
    if (!source) throw new Error(`Missing source ${id}`);
    const label = esc(source.title);
    return source.url ? `<a href="${esc(source.url)}" rel="noopener noreferrer">${label}</a>` : `<span>${label} · ${locale === 'zh' ? '本地留档' : 'local archive'}</span>`;
  }).join(' · ');
}

function evidenceClass(fact) {
  if (fact.validity === 'historical') return 'historical';
  if (fact.evidenceLevel === 'official') return 'evidence-official';
  if (fact.evidenceLevel === 'video-observed') return 'evidence-video';
  if (fact.evidenceLevel === 'community-confirmed') return 'evidence-corroborated';
  return 'evidence-lead';
}

function evidenceLabel(fact, locale) {
  const labels = {
    official: ['Official', '官方'],
    'video-observed': ['Video-observed', '视频观测'],
    'community-confirmed': ['Community-confirmed', '社区互证'],
    'unverified-lead': ['Single-source lead', '单一线索'],
    'build-observed': ['Game-build configuration', '游戏构建配置'],
  };
  return labels[fact.evidenceLevel]?.[locale === 'zh' ? 1 : 0] || fact.evidenceLevel;
}

function nav(locale) {
  const zh = locale === 'zh';
  const links = zh
    ? [['/zh/guides/beginners-guide', '攻略'], ['/zh/database', '资料库'], ['/zh/map', '地图'], ['/zh/problems', '问题'], ['/research', '研究'], ['/zh/search', '搜索'], ['/contribute', '投稿']]
    : [['/guides/beginners-guide', 'Guides'], ['/database', 'Database'], ['/map', 'Map'], ['/problems', 'Problems'], ['/research', 'Research'], ['/search', 'Search'], ['/contribute', 'Contribute']];
  return links.map(([href, label]) => `<li><a href="${href}">${label}</a></li>`).join('');
}

function shell(locale, route, title, description, body) {
  const zh = locale === 'zh';
  const canonical = `https://theranchersguide.com${route}`;
  const alternate = zh ? route.replace(/^\/zh/, '') : `/zh${route}`;
  const normalized = body;
  return `<!DOCTYPE html>
<!-- GENERATED by scripts/build-b2-entries.cjs from data/quests.json and data/materials.json — do not edit directly. -->
<html lang="${zh ? 'zh-CN' : 'en'}"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(title)}</title><meta name="description" content="${esc(description)}"><link rel="canonical" href="${canonical}"><link rel="alternate" hreflang="en" href="https://theranchersguide.com${zh ? alternate : route}"><link rel="alternate" hreflang="zh-CN" href="https://theranchersguide.com${zh ? route : alternate}"><link rel="alternate" hreflang="x-default" href="https://theranchersguide.com${zh ? alternate : route}"><meta property="og:type" content="website"><meta property="og:site_name" content="The Ranchers Guide"><meta property="og:title" content="${esc(title)}"><meta property="og:description" content="${esc(description)}"><meta property="og:url" content="${canonical}"><link rel="icon" type="image/png" sizes="32x32" href="/assets/img/favicon-32.png"><link rel="stylesheet" href="/assets/css/style.css?v=20261003-r15"><link rel="stylesheet" href="/assets/css/database-browser.css?v=20260831-1"><script async src="https://pagead2.googlesyndication.com/pagead/js/adsbygoogle.js?client=ca-pub-4804883741146501" crossorigin="anonymous"></script></head><body class="database-surface">
<header class="site-header"><nav class="nav-inner" aria-label="${zh ? '主导航' : 'Main navigation'}"><a class="logo" href="${zh ? '/zh/' : '/'}"><span class="logo-mark"><img src="/assets/img/logo.png" alt="" width="34" height="34"></span><span>The Ranchers Guide</span></a><button class="nav-toggle" aria-expanded="false" aria-label="${zh ? '打开导航' : 'Toggle navigation'}">☰</button><ul class="nav-links">${nav(locale)}</ul></nav></header>
<main><article class="article database-page b2-entry-page" style="max-width: 980px">${normalized}</article></main>${renderSiteFooter(locale, { en: 'Missing evidence stays visible', zh: '缺失证据保持可见' })}<script src="/assets/js/main.js?v=20261003-r15" defer></script></body></html>`;
}

function relatedLinks(routes, locale) {
  const labels = {
    '/guides/farming-fields': ['Planting & watering', '播种与浇水'],
    '/guides/crafting-guide#recipe-prop_Scarecrow_00': ['Scarecrow materials', '稻草人材料'],
    '/guides/crafting-guide': ['Crafting guide', '制作指南'],
    '/guides/building-construction#materials': ['Building materials', '建造材料'],
    '/guides/resources-and-materials': ['Resources guide', '资源材料指南'],
    '/guides/animal-guide#feeding': ['Chicken feeding', '鸡的喂养'],
    '/database/animals#chicken': ['Chicken evidence', '鸡的证据条目'],
    '/database/quests#seeds-of-success': ['Quest record', '任务记录'],
  };
  return routes.map(route => {
    const label = labels[route] || [route, route];
    return `<a class="btn btn-outline btn-compact" href="${localizeRoute(route, locale)}">${esc(label[locale === 'zh' ? 1 : 0])}</a>`;
  }).join('');
}

function questPage(locale, record) {
  const zh = locale === 'zh';
  const prefix = prefixFor(locale);
  const guide = record.buildGuide;
  const name = zh ? guide.zhName : guide.name;
  const steps = guide.steps.map(step => `<li>${esc(zh ? step.zhText : step.text)}</li>`).join('');
  const notes = (guide.notes || []).map(note => `<li>${esc(zh ? note.zhText : note.text)}</li>`).join('');
  const facts = record.facts.map(fact => `<li><p>${esc(zh ? fact.zhText : fact.text)} <span class="tag ${evidenceClass(fact)}">${evidenceLabel(fact, locale)}</span></p><p class="fact-source"><strong>${zh ? '来源' : 'Source'}:</strong> ${sourceHtml(questsData, fact.sourceIds, locale)} · <strong>${zh ? '版本' : 'Build'}:</strong> ${esc(fact.build || 'not specified')}</p></li>`).join('');
  const body = `<nav class="breadcrumb" aria-label="${zh ? '面包屑' : 'Breadcrumb'}"><a href="${prefix}/">${zh ? '首页' : 'Home'}</a> / <a href="${prefix}/database">${zh ? '资料库' : 'Database'}</a> / <a href="${prefix}/database/quests">${zh ? '任务' : 'Quests'}</a> / ${esc(name)}</nav>
<h1>${esc(name)}</h1><section class="evidence-ledger entity-profile" id="${record.id}" data-search-entry data-search-title="${esc(name)}" data-search-aliases="${esc(`${record.name}|${record.zhName}`)}" data-search-status="${zh ? '任务独立词条' : 'Standalone quest entry'}" data-search-tags="${esc(`${record.searchTags} ${record.zhSearchTags}`)}"><a class="database-back" href="${prefix}/database/quests">${zh ? '返回任务目录' : 'Back to quest database'}</a>
<p class="lead">${esc(zh ? record.zhSummary : record.summary)}</p><div class="database-config"><p><strong>${zh ? '已记录版本' : 'Recorded build reference'}</strong> · ${esc(guide.build)} · ${zh ? '配置记录，未逐项实测' : 'configuration record, not individually play-tested'}</p></div>
<h2>${zh ? '按目标操作' : 'Work through the objectives'}</h2><ol class="evidence-list">${steps}</ol>${notes ? `<h2>${zh ? '容易卡住的判定' : 'Checks that can cause a stop'}</h2><ul class="evidence-list">${notes}</ul>` : ''}
<h2>${zh ? '来源与边界' : 'Sources and boundary'}</h2><ul class="evidence-list">${facts}</ul><p class="database-browse-note">${zh ? '这些步骤来自已记录的游戏构建和公开来源；缺失的奖励、前置条件和解锁时机不会在此补写。' : 'These steps come from the recorded game build and public sources; missing rewards, prerequisites and unlock timing are not filled in.'}</p>
<div class="entity-related"><strong>${zh ? '继续查找' : 'Continue with'}</strong><div>${relatedLinks(record.relatedRoutes || [], locale)}<a class="btn btn-outline btn-compact" href="${prefix}/database/quests#${record.id}">${zh ? '任务数据库原始记录' : 'Original quest record'}</a></div></div></section>`;
  return shell(locale, `${prefix}/database/quests/${record.id}`, `The Ranchers ${name}`, copy(locale, `${name}: objectives, checks & sources`, `${name}：目标、判定与来源`), body);
}

function materialPage(locale, material) {
  const zh = locale === 'zh';
  const prefix = prefixFor(locale);
  const nativeName = zh ? material.zhName.replace(` ${material.name}`, '') : material.name;
  const native = resourceData.items.find(item => item.materialId === material.id);
  const aliases = [material.name, material.zhName, native?.name, native?.zhName].filter(Boolean).join('|');
  const facts = material.facts.map(fact => `<li${fact.validity === 'historical' ? ' class="fact-historical"' : ''}><p>${esc(zh ? fact.zhText : fact.text)} <span class="tag ${evidenceClass(fact)}">${evidenceLabel(fact, locale)}</span></p><p class="fact-source"><strong>${zh ? '来源' : 'Source'}:</strong> ${sourceHtml(materialsData, fact.sourceIds, locale)} · <strong>${zh ? '版本' : 'Build'}:</strong> ${esc(fact.build || 'not specified')}</p></li>`).join('');
  const uses = [];
  for (const entry of buildingEntries.entries) {
    const offer = shops.offers.find(item => item.id === entry.offerId);
    const line = offer?.materials.find(item => materialRoutes[item.id] === material.id);
    if (line) uses.push(`<li><a href="${prefix}/database/buildings/${entry.id}">${zh ? '鸡舍 · Coop' : 'Coop'}</a> × ${line.quantity} ${zh ? '（商店商品记录）' : '(recorded shop offer)'}</li>`);
  }
  const related = relatedLinks(material.relatedRoutes || [], locale);
  const body = `<nav class="breadcrumb" aria-label="${zh ? '面包屑' : 'Breadcrumb'}"><a href="${prefix}/">${zh ? '首页' : 'Home'}</a> / <a href="${prefix}/database">${zh ? '资料库' : 'Database'}</a> / <a href="${prefix}/database/materials">${zh ? '材料' : 'Materials'}</a> / ${esc(nativeName)}</nav>
<h1>${esc(nativeName)}</h1><section class="evidence-ledger material-profile" id="${material.id}" data-search-entry data-search-title="${esc(nativeName)}" data-search-aliases="${esc(aliases)}" data-search-status="${zh ? '材料独立词条' : 'Standalone material entry'}" data-search-tags="${esc(`${material.searchTags} ${material.zhSearchTags}`)}"><a class="database-back" href="${prefix}/database/materials">${zh ? '返回材料目录' : 'Back to materials database'}</a>
<p class="lead">${esc(zh ? material.zhSummary : material.summary)}</p><h2>${zh ? '需要时先看这里' : 'When you need it'}</h2><p>${esc(zh ? material.zhWhenNeeded : material.whenNeeded)}</p><h2>${zh ? '获取与证据' : 'Sources and evidence'}</h2><ul class="evidence-list">${facts}</ul>${uses.length ? `<h2>${zh ? '当前词条中的用途' : 'Uses in current entries'}</h2><ul class="evidence-list">${uses.join('')}</ul>` : ''}<div class="entity-related"><strong>${zh ? '继续查找' : 'Continue with'}</strong><div>${related}<a class="btn btn-outline btn-compact" href="${prefix}/database/materials#${material.id}">${zh ? '材料数据库原始记录' : 'Original material record'}</a></div></div></section>`;
  return shell(locale, `${prefix}/database/materials/${material.id}`, `The Ranchers ${nativeName}`, copy(locale, `${nativeName}: sources, uses & evidence`, `${nativeName}：获取、用途与证据`), body);
}

const questRecords = config.quests.map(id => quests.find(record => record.id === id));
const materialRecords = config.materials.map(id => materials.find(record => record.id === id));
if (questRecords.some(record => !record) || materialRecords.some(record => !record)) throw new Error('B2 entry config references a missing source record');
let failed = false;
for (const locale of ['en', 'zh']) {
  const prefix = prefixFor(locale);
  for (const record of questRecords) {
    const file = path.join(root, locale === 'zh' ? 'zh' : '', 'database', 'quests', `${record.id}.html`);
    const content = questPage(locale, record);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) { console.error(`FAIL: ${file} is out of sync`); failed = true; }
    } else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
  }
  for (const record of materialRecords) {
    const file = path.join(root, locale === 'zh' ? 'zh' : '', 'database', 'materials', `${record.id}.html`);
    const content = materialPage(locale, record);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) { console.error(`FAIL: ${file} is out of sync`); failed = true; }
    } else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
  }
}
if (failed) process.exit(1);
console.log(`PASS: generated ${questRecords.length} quest and ${materialRecords.length} material B2 entries in English and Chinese.`);
